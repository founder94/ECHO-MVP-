export type GuideSectionId = 'start' | 'talk' | 'check' | 'choice' | 'key' | 'zzarit' | 'install' | 'safety' | 'more';

export interface GuideSection {
  id: GuideSectionId;
  /** 목록·메뉴에 보이는 짧은 이름 */
  label: string;
  /** 펼쳤을 때의 제목 */
  title: string;
  /** 본문(3~5문장 · 「요.」로 끝나는 말) */
  body: string;
  /** 순서·버튼 설명 같은 짧은 줄(선택) */
  points?: readonly string[];
  /** 아직 열리지 않은 기능 — 「준비 중」으로 표시 */
  soon?: boolean;
  /** 기능 옆 짧은 도움말(처음 한 번) 한 줄 */
  hint?: string;
}

